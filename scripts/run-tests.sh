#!/usr/bin/env bash
# Runs the automated tests and writes docs/test-results.md from the REAL output.
# Prerequisites: Docker running (database up), the app running in another terminal (npm run dev),
#                Ollama running with nomic-embed-text (otherwise the semantic-search tests are skipped).
# WARNING: RESETS the database first (drops everything, rebuilds, reloads demo passwords).
# Usage: npm run test:all     (or: bash scripts/run-tests.sh)
set -uo pipefail
cd "$(dirname "$0")/.."
if [ -f .env.local ]; then set -a; . ./.env.local; set +a; fi
: "${DATABASE_URL:?DATABASE_URL is not set (copy .env.example to .env.local)}"
BASE="${TV_BASE_URL:-http://localhost:3000}"
export TV_BASE_URL="$BASE" DATABASE_URL

if ! curl -s -m 5 -o /dev/null "$BASE/api/health"; then
  echo "The app is not reachable at $BASE. Start it in another terminal with: npm run dev"; exit 2
fi

psql_file() {  # run a SQL file; extra psql flags as arguments
  local file="$1"; shift
  if command -v psql >/dev/null 2>&1; then psql "$DATABASE_URL" "$@" -f "$file"
  else docker exec -i tracevault-db psql -U tracevault -d tracevault "$@" < "$file"; fi
}

echo ">> Resetting the database and loading demo passwords"
bash scripts/reset-db.sh >/dev/null 2>&1 || { echo "Database reset failed"; exit 2; }
node scripts/make-password-sql.js > sql/local_passwords.sql
psql_file sql/local_passwords.sql -q >/dev/null

TMP="$(mktemp -d)"
echo; echo "=================== DATABASE TESTS (tests/db-tests.sql) ==================="
if ! psql_file tests/db-tests.sql -At -F'|' > "$TMP/db.txt" 2> "$TMP/db-error.txt"; then
  cat "$TMP/db-error.txt" >&2
  echo "Database test execution failed; see the error above." >&2
  exit 2
fi
tr -d '\r' < "$TMP/db.txt" > "$TMP/db-clean.txt"
mv "$TMP/db-clean.txt" "$TMP/db.txt"
grep '^T-DB-' "$TMP/db.txt" | awk -F'|' '{printf "%s  %s  %s\n", $5, $1, $2}'
DB_FAIL=$(grep -c '^T-DB-.*|FAIL$' "$TMP/db.txt" || true)

OLLAMA_ADDR="${OLLAMA_BASE_URL:-${OLLAMA_URL:-http://localhost:11434}}"
if curl -s -m 3 -o /dev/null "$OLLAMA_ADDR"; then
  echo; echo ">> Ollama is running: indexing the seeded incidents (scripts/backfill-embeddings.ts)"
  npx --yes tsx scripts/backfill-embeddings.ts
  bash scripts/apply-vector-index.sh
else
  echo; echo ">> Ollama is not running: the semantic search tests will be skipped"
fi

echo; echo "=================== API TESTS (tests/api.test.mjs) ==================="
node tests/api.test.mjs 2>&1 | tr -d '\r' | tee "$TMP/api_all.txt" | grep -v '^RESULT|'
API_RC=${PIPESTATUS[0]}
grep '^RESULT|' "$TMP/api_all.txt" > "$TMP/api.txt" || true

# ---- write docs/test-results.md ----
mkdir -p docs
OUT="docs/test-results.md"
DB_PASS=$(grep -c '^T-DB-.*|PASS$' "$TMP/db.txt" || true)
A_PASS=$(grep -c '^RESULT|[^|]*|PASS|' "$TMP/api.txt" || true)
A_FAIL=$(grep -c '^RESULT|[^|]*|FAIL|' "$TMP/api.txt" || true)
A_SKIP=$(grep -c '^RESULT|[^|]*|SKIP|' "$TMP/api.txt" || true)
{
  echo "# Automated test results"
  echo
  echo "Generated by \`scripts/run-tests.sh\` on $(date -u +"%Y-%m-%d %H:%M UTC") against $BASE (PostgreSQL + pgvector, freshly seeded)."
  echo
  echo "| Suite | Passed | Failed | Skipped |"
  echo "|---|---|---|---|"
  echo "| Database (tests/db-tests.sql) | $DB_PASS | $DB_FAIL | 0 |"
  echo "| API (tests/api.test.mjs) | $A_PASS | $A_FAIL | $A_SKIP |"
  echo
  echo "## Database tests"
  echo
  echo "| ID | Test | Expected | Actual | Result |"
  echo "|---|---|---|---|---|"
  grep '^T-DB-' "$TMP/db.txt" | awk -F'|' '{printf "| %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5}'
  echo
  echo "## API tests"
  echo
  echo "| ID | Test | Result | Notes |"
  echo "|---|---|---|---|"
  awk -F'|' '{printf "| %s | %s | %s | %s |\n", $2, $4, $3, $5}' "$TMP/api.txt"
} > "$OUT"

echo
echo "=================== SUMMARY ==================="
echo "Database: $DB_PASS passed, $DB_FAIL failed"
echo "API:      $A_PASS passed, $A_FAIL failed, $A_SKIP skipped"
echo "Results written to $OUT"
rm -rf "$TMP"
[ "$DB_FAIL" -eq 0 ] && [ "$A_FAIL" -eq 0 ] && [ "$API_RC" -eq 0 ]
